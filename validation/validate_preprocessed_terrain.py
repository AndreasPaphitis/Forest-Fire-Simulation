    def run_full_validation(self, generate_plots: bool = True) -> Dict[str, Any]:
        """Run the complete validation suite."""
        logger.info("🚀 Starting comprehensive terrain validation...")
        
        try:
            # Run all validation steps
            self.validate_file_integrity()
            self.validate_data_quality()
            self.validate_spatial_consistency()
            self.perform_statistical_analysis()
            
            # Generate plots if requested
            plot_files = []
            if generate_plots:
                plot_files = self.generate_validation_plots()
            
            # Determine overall status
            if self.validation_results['issues']:
                self.validation_results['overall_status'] = 'FAILED'
            elif self.validation_results['warnings']:
                self.validation_results['overall_status'] = 'PASSED_WITH_WARNINGS'
            else:
                self.validation_results['overall_status'] = 'PASSED'
            
            # Add plot files to results
            self.validation_results['plot_files'] = plot_files
            
            logger.info(f"✅ Validation completed with status: {self.validation_results['overall_status']}")
            
        except Exception as e:
            logger.error(f"❌ Validation failed with error: {e}")
            self.validation_results['overall_status'] = 'ERROR'
            self.validation_results['issues'].append(f"Validation error: {e}")
        
        return self.validation_results
    
