        logger.info("📊 Generating validation plots...")
        
        if output_dir is None:
            output_dir = self.preprocessed_dir / "validation_plots"
        
        output_dir = Path(output_dir)
        output_dir.mkdir(exist_ok=True)
        
        plot_files = []
        
        # Create a comprehensive validation figure
        fig, axes = plt.subplots(2, 3, figsize=(18, 12))
        fig.suptitle('Preprocessed Terrain Validation', fontsize=16, fontweight='bold')
        
        # Plot 1: Elevation histogram
