    def save_validation_report(self, output_file: str = None) -> str:
        """Save validation results to a JSON file."""
        if output_file is None:
            output_file = self.preprocessed_dir / "validation_report.json"
        
        # Convert numpy types to native Python types for JSON serialization
        def convert_numpy_types(obj):
            if isinstance(obj, np.integer):
                return int(obj)
            elif isinstance(obj, np.floating):
                return float(obj)
            elif isinstance(obj, np.ndarray):
                return obj.tolist()
            elif isinstance(obj, dict):
                return {str(key): convert_numpy_types(value) for key, value in obj.items()}
            elif isinstance(obj, list):
                return [convert_numpy_types(item) for item in obj]
            elif isinstance(obj, bool):
                return bool(obj)
            elif isinstance(obj, np.bool_):
                return bool(obj)
            else:
                return str(obj) if hasattr(obj, '__class__') else obj
        
        report_data = convert_numpy_types(self.validation_results)
        
        with open(output_file, 'w') as f:
            json.dump(report_data, f, indent=2)
        
        logger.info(f"📄 Validation report saved to: {output_file}")
        return str(output_file)


